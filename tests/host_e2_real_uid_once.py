"""Explicit CachyOS E2 host acceptance: REAL kernel cross-UID, synthetic report.

Manual ONLY after separately approved installation of ai-desktop 0.1.0-3.
Do not include in default CI/LOCAL; invokes sudo -n -u ai-desktop to start
the exact root-owned native CLI, without login shell, OAuth or Claude.
"""
import os
from pathlib import Path
import pwd
import secrets
import select
import socket
import stat
import subprocess
import sys

# Host test imports the exact checked-out SHA; the worker always loads ONLY
# the separately installed root-owned native package under its own UID.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from ai_desktop import e2_account, e2_ipc, e2_worker_once
from ai_desktop.transfer_consent import ConsentSession
from test_report_policy import report_fixture

NATIVE = "/usr/bin/ai-desktop"
EXPECTED_PACKAGE = "ai-desktop 0.1.0-3"
SAFE_STAGES = frozenset({
    "boundary", "preflight-platform", "preflight-account", "preflight-uid",
    "preflight-package", "preflight-ownership", "preflight-sudo", "fixture",
    "positive-worker-start", "positive-worker-ready", "positive-send",
    "positive-worker-ack", "negative-worker-start", "negative-worker-ready",
    "negative-wrong-uid", "negative-worker-exit", "negative-desktop-worker",
    "ready-timeout", "worker-refused-before-bind",
    "worker-exited-before-bind", "worker-unexpected-ready",
    "worker-exit", "worker-reply",
})


def safe_stage(stage):
    return stage if type(stage) is str and stage in SAFE_STAGES else "boundary"


class HostRefusal(RuntimeError):
    """Only fixed, non-sensitive refusal classifications are exposed."""


def require(condition, stage="boundary"):
    if not condition:
        raise HostRefusal(stage)


def command(args):
    result = subprocess.run(args, capture_output=True, text=True,
                            check=False, timeout=5)
    return result.returncode, result.stdout.strip()


def start_worker(token, desktop_uid):
    # All arguments are constants, kernel metadata or random session IDs.
    # sudo must have been authenticated *by the operator* (sudo -v).
    task = subprocess.Popen(
        ["/usr/bin/timeout", "--signal=TERM", "--kill-after=2s", "12s",
         "/usr/bin/sudo", "-n", "-u", "ai-desktop", "--",
         NATIVE, "worker-once", token, str(desktop_uid)],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
        # Keep the operator's controlling TTY for sudoers' per-terminal
        # authentication timestamp. setsid()/start_new_session=True can
        # make sudo -n refuse despite a preceding successful sudo -v.
        bufsize=1,
    )
    return task


def ready(task):
    ready_fds, _, _ = select.select([task.stdout], [], [], 5)
    require(bool(ready_fds), "ready-timeout")
    announcement = task.stdout.readline().strip()
    if announcement == "WORKER: REFUSED":
        raise HostRefusal("worker-refused-before-bind")
    if announcement == "":
        raise HostRefusal("worker-exited-before-bind")
    require(announcement == "WORKER: READY", "worker-unexpected-ready")


def cleanup_worker(task):
    # Let the fixed 12-second timeout reap the sudo-launched worker itself.
    # Killing only the timeout wrapper prematurely could orphan that worker.
    if task.poll() is None:
        task.communicate(timeout=15)


def finish(task, expected_code, expected_output):
    output, error = task.communicate(timeout=15)
    require(task.returncode == expected_code, "worker-exit")
    require(output.strip() == expected_output, "worker-reply")
    # Never display stderr; it may be generated by system components.


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if argv != ["--allow-real-uid-test"]:
        print("HOST CROSS UID: REFUSED (explicit consent flag required)")
        return 2
    stage = "preflight-platform"
    try:
        require(sys.platform == "linux", stage)
        stage = "preflight-account"
        require(os.geteuid() != 0 and e2_account.account_ready(), stage)
        uid = os.geteuid()
        stage = "preflight-uid"
        worker_uid = pwd.getpwnam("ai-desktop").pw_uid
        require(uid != worker_uid and worker_uid > 0, stage)
        stage = "preflight-package"
        code, version = command(["/usr/bin/pacman", "-Q", "ai-desktop"])
        require(code == 0 and version == EXPECTED_PACKAGE, stage)
        stage = "preflight-ownership"
        for path in ("/usr/bin/ai-desktop", "/usr/lib/ai-desktop"):
            meta = os.lstat(path)
            require(meta.st_uid == 0 and not stat.S_ISLNK(meta.st_mode)
                    and not stat.S_IMODE(meta.st_mode) & 0o022, stage)

        # Explicit fixed-command sudo probe; prints only a numeric UID.
        # Distinguishes privilege-policy failures from worker/socket errors.
        stage = "preflight-sudo"
        code, seen_uid = command([
            "/usr/bin/sudo", "-n", "-u", "ai-desktop", "--", "/usr/bin/id", "-u"])
        require(code == 0 and seen_uid == str(worker_uid), "preflight-sudo")

        # Positive case: only synthetic data from a test fixture.
        stage = "fixture"
        report = report_fixture()
        gate = ConsentSession()
        preview = gate.preview(report)
        authorization = gate.authorize(
            report, confirmed_sha256=preview.sha256, nonce=preview.nonce)
        token = secrets.token_hex(16)
        stage = "positive-worker-start"
        worker = start_worker(token, uid)
        try:
            stage = "positive-worker-ready"
            ready(worker)
            stage = "positive-send"
            digest = e2_worker_once.send_once(token, authorization)
            require(digest == preview.sha256, stage)
            stage = "positive-worker-ack"
            finish(worker, 0, "WORKER: RECEIVED sha256=" + digest)
        finally:
            cleanup_worker(worker)

        # Negative case: worker expects a DIFFERENT desktop UID.
        wrong_desktop_uid = uid + 1
        if wrong_desktop_uid == worker_uid:
            wrong_desktop_uid += 1
        token = secrets.token_hex(16)
        stage = "negative-worker-start"
        worker = start_worker(token, wrong_desktop_uid)
        try:
            stage = "negative-worker-ready"
            ready(worker)
            stage = "negative-wrong-uid"

            with socket.socket(socket.AF_UNIX, socket.SOCK_SEQPACKET) as peer:
                peer.settimeout(3)
                peer.connect(e2_worker_once._address(token))
                peer.send(b"synthetic-invalid")
                try:
                    response = peer.recv(80)
                except ConnectionResetError:
                    response = b""
                require(response == b"", stage)  # no ACK for mismatched UID
            stage = "negative-worker-exit"
            finish(worker, 2, "WORKER: REFUSED")
        finally:
            cleanup_worker(worker)

        # Negative case: desktop UID may never impersonate worker.
        stage = "negative-desktop-worker"
        direct = subprocess.run(
            [NATIVE, "worker-once", secrets.token_hex(16), str(uid)],
            capture_output=True, text=True, check=False, timeout=5,
        )
        require(direct.returncode == 2 and
                direct.stdout.strip() == "WORKER: REFUSED", stage)

        print("HOST CROSS UID: PASS worker_uid=" + str(worker_uid) +
              " sender_uid=" + str(uid) + " success=1 refusal=2")
        return 0
    except HostRefusal as exc:
        # Only hardcoded reason codes are emitted, never raw subprocess data.
        print("HOST CROSS UID: REFUSED stage=" + safe_stage(str(exc)))
        return 2
    except (OSError, subprocess.SubprocessError,
            e2_ipc.HandoffDenied, ValueError, KeyError):
        print("HOST CROSS UID: REFUSED stage=" + safe_stage(stage))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
